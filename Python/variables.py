#Variable = a container for a value

name = "Me"

#Strings
print(name)
print(f"My name is {name}")

#Integers
age = 123
print(age)
print(f"I am {age} years old.")

#Float
height = 5.9
print(height)
print(f"I am {height} feet tall.")

#Boolean
is_adult = True
print(is_adult)
print(f"Am I an adult? {is_adult}")
